#!/usr/bin/env python3
"""Generate runtime/src/nvn_procs.inc from nnsdk's nvn.h: one NVN_PROC(name,
kind, nargs) line per NVN entry point, where kind classifies the return value
(void, bool, int32, int64, ptr, float) so the host NVN layer can give every
function a sensible default and hand-write only the ones that matter.

Usage: python -P tools/gen_nvn_procs.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "toolchain", "nnsdk", "lib", "nvn", "include", "nvn")


def kind_of(ret):
    r = ret.strip()
    if r == "void":
        return "void"
    if r == "NVNboolean":
        return "bool"
    if "*" in r or r.startswith("PFNNVN"):
        return "ptr"
    if r in ("float", "double"):
        return "float"
    if r in ("NVNbufferAddress", "NVNcommandHandle", "NVNtextureHandle", "NVNimageHandle", "NVNseparateTextureHandle",
             "NVNseparateSamplerHandle", "uint64_t", "size_t", "ptrdiff_t", "int64_t", "NVNtextureAddress"):
        return "int64"
    return "int32"


def main():
    src = open(os.path.join(INC, "nvn.h"), encoding="utf-8").read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    typedefs = {}
    for m in re.finditer(r"typedef\s+([^;(]+?)\s*\(\s*\*\s*(PFNNVN\w+PROC)\s*\)\s*\(([^;]*?)\)\s*;", src, flags=re.S):
        ret, name, args = m.group(1), m.group(2), " ".join(m.group(3).split())
        nargs = 0 if args in ("", "void") else args.count(",") + 1
        typedefs[name] = (ret, nargs)
    base = open(os.path.join(INC, "nvn_FuncPtrBase.h"), encoding="utf-8").read()
    procs = re.findall(r"extern\s+(PFNNVN\w+PROC)\s+pfnc_(nvn\w+)\s*;", base)
    out = ["// Generated by tools/gen_nvn_procs.py from nnsdk nvn.h - do not edit.",
           "// NVN_PROC(name, return kind, argument count)"]
    missing = 0
    for td, name in procs:
        if td not in typedefs:
            missing += 1
            continue
        ret, nargs = typedefs[td]
        out.append("NVN_PROC(%s, %s, %d)" % (name, kind_of(ret), nargs))
    path = os.path.join(ROOT, "runtime", "src", "nvn_procs.inc")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print("%d NVN procs written (%d without a typedef)" % (len(out) - 2, missing))

    # device info: NVN_DEVICE_INFO_<X> ids paired with the NX constants NVN_DEVICE_<X>
    nx = open(os.path.join(INC, "nvn_DeviceConstantsNX.h"), encoding="utf-8").read()
    consts = dict(re.findall(r"#define\s+NVN_DEVICE_(\w+)\s+(-?\w+)", nx))
    info = re.findall(r"NVN_DEVICE_INFO_(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", src)
    lines = ["// Generated by tools/gen_nvn_procs.py - NVN_DEVINFO(id, value, known, name)"]
    unknown = []
    for name, val in info:
        if name == "LARGE":
            continue
        v = consts.get(name)
        if v is None:
            unknown.append(name)
        lines.append('NVN_DEVINFO(%s, %s, %d, "%s")' % (val, v if v is not None else "0", v is not None, name))
    with open(os.path.join(ROOT, "runtime", "src", "nvn_devinfo.inc"), "w", newline="\n") as fp:
        fp.write("\n".join(lines) + "\n")
    print("%d device info ids, %d without an NX constant: %s" % (len(lines) - 1, len(unknown), ", ".join(unknown)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
